import assert from "node:assert/strict";
import type { PrismaClient } from "../src/generated/prisma/client";
import type pg from "pg";

// Invoked by the settlement integration harness in its disposable schema.
export async function checkNotifications(db: PrismaClient, control: pg.Client, users: { id: string; cookie: string }[], auctionId: string, base: string) {
  const [a, b] = users;
  const { runNotificationBatch, myNotifications, recordWorkerPoll } = await import("../src/modules/notifications/service");
  const { GET } = await import("../src/app/api/v1/notifications/route");
  const { POST } = await import("../src/app/api/v1/notifications/[id]/read/route");
  const { GET: operations } = await import("../src/app/api/v1/admin/operations/route");
  const events = await db.notificationOutbox.findMany({ where: { auctionId } });
  assert.equal(events.filter(row => row.kind === "OFFER_CREATED").length, 2);
  assert.equal(events.filter(row => row.kind === "OFFER_EXPIRED").length, 1);
  assert.equal(events.filter(row => row.kind === "WINNER_CONFIRMED").length, 1);
  assert.equal(await db.notification.count(), 0, "Saving an event does not pretend delivery already happened.");
  const transferCount = await db.walletTransfer.count();
  const offerCount = await db.winnerOffer.count();
  const readRequest = (cookie = a.cookie, query = "") => new Request(`${base}/api/v1/notifications${query}`, { headers: { Cookie: cookie } });
  assert.equal((await GET(readRequest(""))).status, 401);
  // Failure after claiming an event must leave it pending with a safe retry.
  await control.query("CREATE FUNCTION notification_test_failure() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN RAISE EXCEPTION 'Disposable delivery failure'; END $$");
  await control.query('CREATE TRIGGER notification_test_failure BEFORE INSERT ON "Notification" FOR EACH ROW EXECUTE FUNCTION notification_test_failure()');
  assert.deepEqual(await runNotificationBatch(1), ["retry-scheduled"]);
  assert.equal(await db.notification.count(), 0);
  const failed = (await db.notificationOutbox.findFirst({ where: { lastError: "DELIVERY_FAILED" } }))!;
  assert.equal(failed.attempts, 1); assert.equal(failed.deliveredAt, null); assert.ok(failed.nextAttemptAt > failed.createdAt);
  await db.user.update({ where: { id: a.id }, data: { role: "ADMIN" } });
  const opsRequest = (cookie = a.cookie, query = "") => new Request(`${base}/api/v1/admin/operations${query}`, { headers: { Cookie: cookie } });
  assert.equal((await operations(opsRequest(""))).status, 401);
  assert.equal((await operations(opsRequest(b.cookie))).status, 403);
  assert.equal((await operations(opsRequest(a.cookie, "?view=invalid"))).status, 400);
  await recordWorkerPoll("settlement"); await recordWorkerPoll("notifications");
  const opsResponse = await operations(opsRequest()); assert.equal(opsResponse.status, 200);
  assert.equal(opsResponse.headers.get("cache-control"), "private, no-store");
  const ops = await opsResponse.json(); assert.equal(ops.counts.notificationRetrying, 1); assert.equal(ops.workers.length, 2);
  assert.ok(ops.deliveryFailures.every((row: Record<string, unknown>) => !row.userId && !row.body));
  const { checkOperationRetries } = await import("./operation-retry-checks");
  await checkOperationRetries(db, control, users, failed.id, base);
  await control.query('DROP TRIGGER notification_test_failure ON "Notification"');
  await control.query("DROP FUNCTION notification_test_failure()");
  await db.notificationOutbox.update({ where: { id: failed.id }, data: { nextAttemptAt: new Date(0) } });
  const batches = await Promise.all([runNotificationBatch(), runNotificationBatch(), runNotificationBatch()]);
  assert.equal(batches.flat().filter(result => result === "retry-scheduled").length, 0);
  const eventCount = await db.notificationOutbox.count();
  assert.equal(await db.notification.count(), eventCount);
  assert.equal(await db.notificationOutbox.count({ where: { deliveredAt: null } }), 0);
  assert.deepEqual(await runNotificationBatch(), []);
  const { POST: retryDelivery } = await import("../src/app/api/v1/admin/operations/retry/route");
  const deliveredRetry = await retryDelivery(new Request(`${base}/api/v1/admin/operations/retry`, { method: "POST", headers: { Cookie: a.cookie, Origin: base, "Content-Type": "application/json" }, body: JSON.stringify({ kind: "notification", id: failed.id, expectedAttempts: 3, reason: "Delivery already completed", reference: "delivered-retry-001" }) }));
  assert.equal(deliveredRetry.status, 409, "Delivered notifications cannot be reopened.");
  assert.equal(await db.walletTransfer.count(), transferCount, "Delivery never repeats payments/refunds.");
  assert.equal(await db.winnerOffer.count(), offerCount);
  const first = (await myNotifications(a.id)).items[0];
  const other = (await myNotifications(b.id)).items[0];
  assert.ok(first && other);
  const initialUnread = (await myNotifications(a.id)).unreadCount;
  const markRequest = (cookie = a.cookie, origin = base, body: unknown = {}) => new Request(`${base}/api/v1/notifications/${first.id}/read`, { method: "POST", headers: { Cookie: cookie, Origin: origin, "Content-Type": "application/json" }, body: JSON.stringify(body) });
  const context = { params: Promise.resolve({ id: first.id }) };
  assert.equal((await POST(markRequest(""), context)).status, 401);
  assert.equal((await POST(markRequest(b.cookie), context)).status, 404);
  assert.equal((await POST(markRequest(a.cookie, "https://untrusted.example"), context)).status, 403);
  assert.equal((await POST(markRequest(a.cookie, base, { userId: b.id }), context)).status, 400);
  const marks = await Promise.all([POST(markRequest(), context), POST(markRequest(), context)]);
  const marked = await Promise.all(marks.map(async response => { assert.equal(response.status, 200); return response.json(); }));
  assert.equal(marked[0].readAt, marked[1].readAt);
  assert.equal((await myNotifications(a.id)).unreadCount, initialUnread - 1);
  const owned = await GET(readRequest(a.cookie, `?userId=${b.id}`)); assert.equal(owned.status, 200);
  assert.ok(!(await owned.json()).items.some((item: { id: string }) => item.id === other.id));
  assert.equal((await GET(readRequest(a.cookie, `?before=${other.id}`))).status, 400);
  await assert.rejects(db.notification.update({ where: { id: first.id }, data: { userId: b.id } }));
  await assert.rejects(db.notification.update({ where: { id: first.id }, data: { readAt: null } }));
  await assert.rejects(db.notification.create({ data: { eventId: failed.id, userId: b.id } }));
  await db.notificationOutbox.createMany({ data: Array.from({ length: 25 }, (_, index) => ({ eventKey: `page-fixture-${index}`, userId: a.id, auctionId, kind: "OFFER_EXPIRED" as const, title: "Pagination fixture", body: "Disposable notification pagination fixture.", href: "/offers" })) });
  await runNotificationBatch();
  const page1 = await myNotifications(a.id); assert.equal(page1.items.length, 20); assert.ok(page1.nextCursor);
  const page2 = await myNotifications(a.id, page1.nextCursor!); assert.ok(page2.items.length > 0);
  assert.equal(new Set([...page1.items, ...page2.items].map(item => item.id)).size, page1.items.length + page2.items.length);
  const completedOps = await operations(opsRequest(a.cookie, "?view=completed")); assert.equal(completedOps.status, 200);
  const completed = await completedOps.json();
  assert.ok(completed.jobs.some((job: { auctionId: string; status: string }) => job.auctionId === auctionId && job.status === "WINNER_CONFIRMED"));
  assert.ok(completed.jobs.filter((job: { status: string }) => job.status === "REFUNDED").every((job: { bidCount: number; refundedBidCount: number }) => job.bidCount === job.refundedBidCount));
  await db.user.update({ where: { id: a.id }, data: { role: "USER" } });
  assert.equal((await operations(opsRequest())).status, 403);
  await db.user.update({ where: { id: a.id }, data: { status: "SUSPENDED" } });
  assert.equal((await GET(readRequest())).status, 403); assert.equal((await POST(markRequest(), context)).status, 403);
  await db.user.update({ where: { id: a.id }, data: { status: "ACTIVE" } });
  console.log("PASS: transactional notification events, concurrent delivery deduplication, failure/backoff/recovery, no repeated finances, inbox ownership/pagination/read states, admin monitoring, heartbeats, and permissions.");
}
